// Run explicitly with an installed Playwright module; synthetic data only.
// PLAYWRIGHT_MODULE=/absolute/playwright/index.mjs node .../eval-ui-smoke.mjs
import assert from "node:assert/strict";
import { mkdtemp, realpath, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, isAbsolute } from "node:path";
import { pathToFileURL } from "node:url";
import { startTraceDashboard } from "./dashboard.mjs";
import { fixtureSession, ATTACK } from "./eval-fixtures.mjs";
if (!isAbsolute(process.env.PLAYWRIGHT_MODULE ?? "")) throw new Error("Set PLAYWRIGHT_MODULE to the installed Playwright entry");
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const directory = await realpath(await mkdtemp(join(tmpdir(), "rotom-eval-ui-")));
const root = join(directory, "sessions"), evalDirectory = join(directory, "private");
await fixtureSession(root, "synthetic-idle", { large: true });
await fixtureSession(root, "synthetic-active", { active: true });
const dashboard = await startTraceDashboard({ root, evalDirectory });
let browser;
const errors = [], external = [];
try {
	// Installed Chrome in a fresh Playwright profile, never the user's profile.
	browser = await chromium.launch({ channel: "chrome", headless: true });
	const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
	page.on("pageerror", (error) => errors.push(error.message));
	page.on("request", (request) => { if (!request.url().startsWith(dashboard.baseUrl)) external.push(request.url()); });
	await page.goto(dashboard.url);
	assert.equal(await page.locator("#eval-workspace").isVisible(), false);
	const scriptCount = await page.locator("script").count();
	await page.getByRole("button", { name: "Eval", exact: true }).click();
	await page.locator("#eval-filter").selectOption("unlabeled");
	// A failed older selection must not replace the newer session's detail.
	let pendingRoute, signalHeld;
	const held = new Promise((resolve) => { signalHeld = resolve; });
	const idleRoute = "**/api/eval/session?id=synthetic-idle";
	await page.route(idleRoute, (route) => { pendingRoute = route; signalHeld(); });
	await page.locator('[data-session-id="synthetic-idle"]').click();
	await held;
	await page.locator('[data-session-id="synthetic-active"]').click();
	await page.getByText("会话进行中，暂不能标注", { exact: true }).waitFor();
	const oldResponse = page.waitForResponse((response) => response.url().endsWith("id=synthetic-idle"));
	await pendingRoute.fulfill({ status: 500, contentType: "application/json", body: '{"error":"synthetic_late_failure"}' });
	await (await oldResponse).finished();
	await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
	assert.equal(await page.locator("#eval-pass").isDisabled(), true);
	await page.unroute(idleRoute);
	await page.locator('[data-session-id="synthetic-idle"]').click();
	await page.getByRole("heading", { name: "当前分支时间线" }).waitFor();
	assert.ok((await page.locator("#eval-workspace").textContent()).includes(ATTACK.slice(0, 45)));
	assert.equal(await page.locator("script").count(), scriptCount);
	assert.equal(await page.locator("img").count(), 0);
	assert.equal(await page.evaluate(() => globalThis.evalInjected), undefined);
	assert.equal(await page.locator("details[open]").count(), 0);
	await page.getByText("工具参数", { exact: true }).click();
	assert.ok((await page.locator("details[open]").textContent()).includes("已截断"));
	await page.getByText("工具结果", { exact: true }).click();
	await page.getByText("第一次出错", { exact: true }).waitFor();
	await page.locator("#eval-fail").click();
	await page.locator("#eval-note").fill("合成用例：边界结果不符合预期");
	await page.locator("#eval-failset").check();
	await page.locator("#eval-save").click();
	await page.getByText("标注已保存", { exact: true }).waitFor();
	await page.screenshot({ path: join(directory, "eval-review.png"), fullPage: true });
	const stored = JSON.parse(await readFile(join(evalDirectory, "annotations/synthetic-idle.json"), "utf8"));
	assert.equal(stored.verdict, "fail"); assert.equal(stored.failSet, true);
	await page.locator("#eval-timeline").evaluate((node) => node.scrollIntoView({ block: "start" }));
	await page.screenshot({ path: join(directory, "eval-timeline.png"), fullPage: true });
	await page.getByRole("button", { name: "下一页事件", exact: true }).click();
	await page.locator('.eval-event[data-index="20"]').waitFor();
	await page.reload();
	await page.getByRole("button", { name: "Eval", exact: true }).click();
	await page.locator("#eval-filter").selectOption("failSet");
	await page.locator('[data-session-id="synthetic-idle"]').click();
	await page.locator("#eval-note").waitFor();
	assert.equal(await page.locator("#eval-note").inputValue(), stored.note);
	assert.equal(await page.locator("#eval-failset").isChecked(), true);
	await page.screenshot({ path: join(directory, "eval-failset.png"), fullPage: true });
	await page.locator("#eval-filter").selectOption("unlabeled");
	await page.locator('[data-session-id="synthetic-active"]').click();
	await page.getByText("会话进行中，暂不能标注", { exact: true }).waitFor();
	assert.equal(await page.locator("#eval-pass").isDisabled(), true);
	assert.equal(await page.locator("#eval-save").isDisabled(), true);
	await page.setViewportSize({ width: 390, height: 844 });
	const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].filter((node) => node.getBoundingClientRect().right > innerWidth + 1).slice(0, 8).map((node) => ({ tag: node.tagName, cls: node.className, width: node.getBoundingClientRect().width })));
	assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, JSON.stringify(overflow));
	await page.screenshot({ path: join(directory, "eval-active-mobile.png"), fullPage: true });
	await page.getByRole("button", { name: "EXECUTION TRACE", exact: true }).click();
	assert.equal(await page.locator("#eval-workspace").isVisible(), false);
	assert.equal(await page.locator(".workspace").isVisible(), true);
	assert.deepEqual(errors, []); assert.deepEqual(external, []);
	console.log(JSON.stringify({ status: "PASS", screenshots: ["eval-review.png", "eval-timeline.png", "eval-failset.png", "eval-active-mobile.png"].map((name) => join(directory, name)), pageErrors: errors.length, externalRequests: external.length }));
} finally {
	await browser?.close(); await dashboard.close();
	await rm(root, { recursive: true, force: true });
	await rm(evalDirectory, { recursive: true, force: true });
}
