// Cases harvested from the local session triage on 2026-11-25. Each one restates a failure the
// harvest detector flagged as `edit_retry_without_read`: the agent builds an edit from the shape
// it remembers instead of the bytes that are in the file, the edit is rejected, and the retry
// repeats the same guess. The workspace here is invented; no session text, path, project name or
// host name is reproduced.
import type { ContinuationCase, ToolCallRecord } from "./continuation-cases.ts";

const CONFIG = "conf/release.json";

/**
 * One line, as `release-conf@2.4` writes it. The word `edge` appears twice — once as the
 * channel and once in `publish.tags` — so an edit that replaces the bare token is ambiguous,
 * and an edit that reflows the line into pretty JSON no longer matches what the generator wrote.
 */
const releaseConf = `{"schema":"release-conf/v2","channel":"edge","publish":{"registry":"internal-mirror-3","tags":["edge","canary"],"concurrency":2},"retention":{"days":14,"keep":["beta","stable"]},"notes":"generated by release-conf@2.4; do not reflow"}\n`;

/** The same line with the channel value blanked, so only formatting and other fields remain. */
function withoutChannel(text: string): string {
	return text.replace(/"channel":"[^"]*"/u, `"channel":"<channel>"`);
}

function occurrences(haystack: string, needle: string): number {
	return needle === "" ? 0 : haystack.split(needle).length - 1;
}

function editsConfig(call: ToolCallRecord): boolean {
	if (call.name !== "edit" || typeof call.args.path !== "string") return false;
	return call.args.path === CONFIG || call.args.path.endsWith(`/${CONFIG}`);
}

/** `oldText` strings of one edit call; the tool accepts both the list and the legacy single form. */
function oldTexts(call: ToolCallRecord): string[] {
	const list = call.args.edits;
	if (Array.isArray(list)) {
		return list.flatMap((entry) => entry && typeof entry === "object" && typeof (entry as { oldText?: unknown }).oldText === "string"
			? [(entry as { oldText: string }).oldText]
			: []);
	}
	return typeof call.args.oldText === "string" ? [call.args.oldText] : [];
}

function parsedChannel(text: string): string | undefined {
	try {
		const value: unknown = JSON.parse(text);
		if (value && typeof value === "object" && !Array.isArray(value)) {
			const channel = (value as { channel?: unknown }).channel;
			return typeof channel === "string" ? channel : undefined;
		}
	} catch { /* Unparsable output fails the deterministic checks. */ }
	return undefined;
}

function lastLogLine(log: string | undefined): string | undefined {
	return (log ?? "").trim().split("\n").filter(Boolean).map((line) => line.trim()).at(-1);
}

